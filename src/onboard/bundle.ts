import { stringify } from "yaml";
import { sha256 } from "../landing/policy.ts";
import { parseAdapterDoc, type TrackerConfig } from "../tracker/config.ts";
import type { OnboardHost, OpenedPr } from "./host.ts";
import type { Proposal } from "./propose.ts";

export const BUNDLE_PATHS = {
  policy: ".agents/abt/merge-policy.yaml",
  facts: ".agents/abt/facts.yaml",
  adapter: ".agents/abt/workflow.md",
  landTree: ".agents/abt/trees/land.yaml",
  claude: "CLAUDE.md",
} as const;

/** The one line CLAUDE.md gets: where the project's abt files live. */
export const CLAUDE_POINTER = "abt: this project's merge policy and workflow adapter live in `.agents/abt/` (see `.agents/abt/workflow.md`); they are pinned, so change them only through a PR the owner merges by hand.";

export interface BundleInput {
  proposal: Proposal;
  /** The tracker the project uses; states and labels take the defaults unless given. */
  tracker: Pick<TrackerConfig, "team" | "credentials"> & Partial<Pick<TrackerConfig, "states" | "labels">>;
  /** The land tree the policy is agreed with, as a file. */
  landTree: string;
  /** The project's CLAUDE.md as it is now; absent when it has none. */
  claudeMd?: string;
}

export interface Bundle {
  /** Path -> content, every file the onboarding PR adds or changes. */
  files: Record<string, string>;
}

const DEFAULT_STATES = { Todo: "Todo", "In progress": "In Progress", "In review": "In Review", "Needs you": "Needs You", Done: "Done", Abandoned: "Canceled" };

function adapterDoc(t: BundleInput["tracker"]): string {
  const front = stringify({ tracker: { kind: "linear", team: t.team, credentials: t.credentials, states: t.states ?? DEFAULT_STATES, ...(t.labels && { labels: t.labels }) } });
  const doc = `---\n${front}---\n\n# abt workflow adapter\n\nGenerated by \`abt onboard\`. Only the front matter is read.\n`;
  parseAdapterDoc(doc); // never generate a doc the runner would refuse
  return doc;
}

function withPointer(claudeMd: string | undefined): string {
  if (claudeMd === undefined || claudeMd.trim() === "") return `${CLAUDE_POINTER}\n`;
  if (claudeMd.split("\n").includes(CLAUDE_POINTER)) return claudeMd;
  return `${claudeMd.replace(/\n*$/, "\n")}\n${CLAUDE_POINTER}\n`;
}

/** The files the onboarding PR carries: policy (hashed to the land tree), facts snapshot, land tree, adapter doc, CLAUDE.md pointer. */
export function buildBundle(input: BundleInput): Bundle {
  const { proposal } = input;
  const facts = stringify({ captured_at: proposal.policy.facts.captured_at, ...proposal.facts, missing: proposal.missing });
  const policy = stringify({
    ...proposal.policy,
    facts: { ...proposal.policy.facts, snapshot_hash: sha256(facts) },
    land_tree_hash: sha256(input.landTree),
  });
  return {
    files: {
      [BUNDLE_PATHS.policy]: policy,
      [BUNDLE_PATHS.facts]: facts,
      [BUNDLE_PATHS.landTree]: input.landTree,
      [BUNDLE_PATHS.adapter]: adapterDoc(input.tracker),
      [BUNDLE_PATHS.claude]: withPointer(input.claudeMd),
    },
  };
}

function prBody(p: Proposal): string {
  const lines = [
    `Onboarding ${p.facts.id}: proposed preset **${p.preset}**${p.named !== p.preset ? ` (facts point to ${p.named}, named only in v1)` : ""}, merge action ${p.mergeAction}.`,
    "",
    ...p.reasons.map((r) => `- ${r}`),
    "",
    "Until you merge this PR by hand the project is pr-only. On that merge the runner pins the protected files outside the repo; a later change to one without a new pin puts the project in Needs you.",
  ];
  if (p.gaps.length > 0) lines.push("", "Evidence gaps (modules with no covered check):", ...p.gaps.map((g) => `- ${g.path}: ${g.reason}`));
  return lines.join("\n");
}

/** Opens the PR that carries the bundle. Never merges it: the human does. */
export function openOnboardingPr(host: OnboardHost, proposal: Proposal, bundle: Bundle): Promise<OpenedPr> {
  return host.openPr({ branch: "abt/onboarding", title: "chore(abt): onboard the project to abt", body: prBody(proposal), files: bundle.files });
}
